import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mkdirSync,rmSync,writeFileSync} from 'node:fs';
import {littleWorlds,generateLittle} from '../src/preschool-engine.js';

const texts=new Set([
  'Hi Pranav! Let’s find something fun to discover.',
  'You found it!',
  'Good try. Let’s look again.',
  'Tap the balloon to keep it up!',
  'Amazing! Keep it up!',
  'Go little snake! Find a colorful shape.',
  'Snip! Grow again!',
  'Amazing! Your snake is growing!',
  'Collect the colorful shapes and grow!',
]);
for(const skill of littleWorlds.flatMap(world=>world.skills))for(const level of [1,2])for(let seed=1;seed<=1000;seed++)texts.add(generateLittle(skill,level,seed).spoken);
const out=new URL('../public/voice/flo/',import.meta.url),tmp=new URL('../.voice-tmp/',import.meta.url);mkdirSync(out,{recursive:true});mkdirSync(tmp,{recursive:true});
const clips={};
for(const text of [...texts].sort()){
  const id=createHash('sha1').update(text).digest('hex').slice(0,14),aiff=new URL(`${id}.aiff`,tmp),m4a=new URL(`${id}.m4a`,out);
  const spoken=spawnSync('say',['-v','Flo (English (US))','-r','170','-o',aiff.pathname,text]);if(spoken.status!==0)throw Error(spoken.stderr.toString());
  const converted=spawnSync('afconvert',['-f','m4af','-d','aac','-b','48000',aiff.pathname,m4a.pathname]);if(converted.status!==0)throw Error(converted.stderr.toString());
  clips[text]=`/voice/flo/${id}.m4a`;
}
writeFileSync(new URL('../src/natural-voice-clips.js',import.meta.url),`// Generated by scripts/generate-natural-voice.mjs\nexport const naturalVoiceClips=${JSON.stringify(clips,null,2)};\n`);
rmSync(tmp,{recursive:true,force:true});
console.log(`Generated ${Object.keys(clips).length} warm voice clips.`);
